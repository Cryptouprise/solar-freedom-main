CREATE TABLE `autonomousWorkItems` (
	`id` int AUTO_INCREMENT NOT NULL,
	`workKey` varchar(191) NOT NULL,
	`kind` varchar(32) NOT NULL,
	`agentSlug` varchar(50),
	`pipelineId` int,
	`scheduleCronTaskUid` varchar(65),
	`status` enum('queued','leased','completed','blocked','failed') NOT NULL DEFAULT 'queued',
	`stateJson` text,
	`attempts` int NOT NULL DEFAULT 0,
	`steps` int NOT NULL DEFAULT 0,
	`failures` int NOT NULL DEFAULT 0,
	`priority` int NOT NULL DEFAULT 50,
	`nextRunAt` timestamp NOT NULL DEFAULT (now()),
	`leaseToken` varchar(64),
	`leaseUntil` timestamp,
	`resultSummary` text,
	`errorMessage` text,
	`finishedAt` timestamp,
	`createdAt` timestamp NOT NULL DEFAULT (now()),
	`updatedAt` timestamp NOT NULL DEFAULT (now()) ON UPDATE CURRENT_TIMESTAMP,
	CONSTRAINT `autonomousWorkItems_id` PRIMARY KEY(`id`),
	CONSTRAINT `autonomousWorkItems_workKey_unique` UNIQUE(`workKey`)
);
